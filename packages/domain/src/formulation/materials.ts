export type MaterialPhase = 'water' | 'oil' | 'cool_down' | 'concentrate' | 'solvent'

export type Material = {
  inci: string
  /** Trade or common names people type instead of the INCI. */
  aliases?: string[]
  cas?: string
  roles: MaterialRole[]
  phase: MaterialPhase
  /** Usual use band, % w/w of the finished product. */
  typical: [number, number]
  /** Hard ceiling (regulatory or technical). Above this the draft is rejected. */
  max?: number
  solubility: 'water' | 'oil' | 'both' | 'alcohol'
  /** Add below 40 °C. */
  coolDown?: boolean
  animalDerived: TriStateFlag
  originType: IngredientOriginType
  /** EU fragrance allergen — must appear on the label above the threshold. */
  allergen?: boolean
  /** Short process or compatibility note the agent can pass on. */
  notes?: string
}

