/**
 * Formulation knowledge, separate from the shelf.
 *
 * Inventory answers "what do I own". This library answers "what exists, what it does,
 * and how much of it belongs in a finished product". The agent fills a skeleton from
 * here; the inventory only flags what needs ordering.
 *
 * Percents are % w/w of the finished product. Perfume aroma materials are given at
 * finished-product level for an eau de parfum (concentrate 15–25%).
 */

