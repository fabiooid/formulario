const MATERIAL_INDEX: Map<string, Material> = (() => {
  const index = new Map<string, Material>()
  for (const material of MATERIALS) {
    index.set(normalizeInci(material.inci), material)
    for (const alias of material.aliases ?? []) {
      const key = normalizeInci(alias)
      if (!index.has(key)) index.set(key, material)
    }
  }
  return index
})()

/** Match an INCI or a known trade/common name to a library material. */
export function findMaterial(inci: string): Material | undefined {
  const key = normalizeInci(inci).replace(/\s+/g, ' ')
  return MATERIAL_INDEX.get(key)
}

/** Every name a material may be filed under on the shelf: its INCI plus known aliases. */
export function materialKeys(material: Material): string[] {
  return [material.inci, ...(material.aliases ?? [])].map((name) => normalizeInci(name))
}

/**
 * Look a row up on the shelf. The shelf may say "Shea Butter" while the row says
 * "Butyrospermum Parkii Butter", so try the INCI, then every alias the library knows.
 */
export function findOnShelf<T extends { inci: string }>(inci: string, shelf: T[], material = findMaterial(inci)): T | undefined {
  const keys = new Set([normalizeInci(inci), ...(material ? materialKeys(material) : [])])
  return shelf.find((item) => keys.has(normalizeInci(item.inci)))
}

export function materialsForRole(role: MaterialRole): Material[] {
  return MATERIALS.filter((material) => material.roles.includes(role))
}

export function searchMaterials(query: string, options?: { role?: MaterialRole; limit?: number }) {
  const q = normalizeInci(query)
  const limit = options?.limit ?? 20
  const matches = MATERIALS.filter((material) => {
    if (options?.role && !material.roles.includes(options.role)) return false
    if (!q) return true
    return (
      normalizeInci(material.inci).includes(q) ||
      (material.aliases ?? []).some((alias) => normalizeInci(alias).includes(q)) ||
      material.roles.some((role) => role.includes(q) || MATERIAL_ROLE_LABELS[role].toLowerCase().includes(q)) ||
      (material.notes ?? '').toLowerCase().includes(q)
    )
  })
  return matches.slice(0, limit)
}
